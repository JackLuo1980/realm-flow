def pick(options: list[str], key: str) -> str:
    digest = hashlib.md5(key.encode("utf-8")).hexdigest()
    return options[int(digest[:8], 16) % len(options)]


def extract_org(project_name: str) -> str:
    name = str(project_name or "")
    for pat in [r"^(.+?银行)", r"^(.+?农商银行)", r"^(.+?农商行)", r"^(.+?金租)", r"^(.+?保险)"]:
        m = re.match(pat, name)
        if m:
            return m.group(1)
    return ""


def org_scene(org: str) -> str:
    text = org or ""
    if "农商" in text or "农信" in text:
        return "县域和分支机构较多，通常更看重口径统一、结果可追溯和日常管理效率"
    if "金租" in text:
        return "租赁业务链条较长，通常更关注资产分类、风险计量和监管输出的一致性"
    if any(k in text for k in ["平安银行", "招商银行", "中信银行", "兴业银行", "广发银行", "恒丰银行"]):
        return "业务条线较多，通常更强调跨系统协同、数据一致性和结果时效"
    if "银行" in text:
        return "多源系统并存，通常更关注指标口径统一、结果核对和报送效率"
    return "项目场景通常会更关注数据统一、流程衔接和后续使用便利性"


def project_family(name: str) -> str:
    n = str(name or "")
    mapping = [
        (["资本新规", "资本管理", "RWA", "ICAAP", "资本"], "capital"),
        (["风险集市", "集市"], "market"),
        (["风险客户标签", "标签"], "tag"),
        (["审计画像", "画像"], "audit"),
        (["表外监测", "监测"], "monitor"),
        (["智慧风控", "风控", "决策", "反欺诈"], "decision"),
        (["风险管理", "风险管控", "操作风险", "风险"], "risk"),
        (["合规网格", "合规"], "compliance"),
        (["压力测试"], "stress"),
        (["并表"], "merge"),
        (["限额"], "limit"),
        (["模型"], "model"),
        (["监管", "报表"], "report"),
        (["托管", "清算"], "custody"),
        (["催收"], "collection"),
        (["零售", "营销"], "retail"),
        (["数据", "数仓", "中台", "大数据"], "data"),
    ]
