def build_experience(project_name: str, person: str) -> str:
    key = f"{person}|{project_name}"
    first = pick(project_intro(project_name), key + "|a")
    second = pick(project_scope(project_name), key + "|b")
    third = pick(project_result(project_name), key + "|c")
    return f"{first}{second}{third}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("workbook")
    args = parser.parse_args()

    path = Path(args.workbook)
    wb = load_workbook(path)
    detail = wb["主要经历工作经历"]
    headers = [detail.cell(1, c).value for c in range(1, detail.max_column + 1)]
    if "项目经验" in headers:
        exp_col = headers.index("项目经验") + 1
    else:
        exp_col = detail.max_column + 1
        detail.cell(1, exp_col).value = "项目经验"

    name_col = headers.index("人员姓名") + 1
    company_col = headers.index("公司名称") + 1
    proj_col = headers.index("项目名称及项目内容") + 1

    for r in range(2, detail.max_row + 1):
        company = detail.cell(r, company_col).value
        if str(company or "").strip() != TARGET_COMPANY:
            detail.cell(r, exp_col).value = ""
            continue
        person = str(detail.cell(r, name_col).value or "")
        project_name = str(detail.cell(r, proj_col).value or "")
        detail.cell(r, exp_col).value = build_experience(project_name, person)

    wb.save(path)
    print(f"updated {path}")


if __name__ == "__main__":
    main()
